"""
macro_simulations.py

Macroeconomic simulation module for the Italian population projection Streamlit app.

Reads all required data from the 'macro/' subfolder generated by extract_macro_data.R:
  macro/df_output.csv
  macro/df_debt.csv
  macro/mod_*_coef.csv   (9 model coefficient files)
  macro/resid_*.csv      (9 residual matrices, 25 rows = 2000-2024 window)

Cross-country interest-rate chain: US → Germany → peripheral countries
(France, Italy, Netherlands, Spain).

Simulation is vectorised across Monte Carlo paths; only the year loop is sequential.
"""

from __future__ import annotations

import os
import warnings
from typing import Dict

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

COUNTRY_ORDER = ["US", "Germany", "France", "Italy", "Netherlands", "Spain"]
PERIPHERAL    = ["France", "Italy", "Netherlands", "Spain"]
LARGE_FIGSIZE = (13.5, 7.4)
SCENARIO_COLORS = ["#1f77b4", "#ff7f0e", "#2ca02c", "#d62728"]

VAR_LABELS = {
    "dy":           "Real GDP Growth Rate",
    "g":            "Nominal Growth Rate",
    "pi":           "Inflation",
    "ir":           "Nominal Cost of Debt",
    "b":            "Debt-to-GDP Ratio",
    "s":            "Primary Surplus (% GDP)",
    "s_social":     "Social Surplus (% GDP)",
    "s_non_social": "Non-Social Surplus (% GDP)",
    "ygap":         "Output Gap",
}


# ---------------------------------------------------------------------------
# Data loading
# ---------------------------------------------------------------------------

def _macro_dir(rdata_path: str) -> str:
    """Return the macro/ subfolder next to rdata_path."""
    return os.path.join(os.path.dirname(os.path.abspath(rdata_path)), "macro")


def _require_macro_dir(macro_dir: str) -> None:
    if not os.path.isdir(macro_dir):
        raise FileNotFoundError(
            f"macro/ folder not found at {macro_dir}.\n"
            "Run extract_macro_data.R once in R/RStudio to generate it."
        )


def load_macro_data(rdata_path: str) -> pd.DataFrame:
    """
    Load df_output.csv and df_debt.csv from the macro/ subfolder, merge them,
    fill PTR_US, and return df_proj filtered to Year > 1970.

    Pre-requisite: run extract_macro_data.R once to populate macro/.
    """
    macro_dir = _macro_dir(rdata_path)
    _require_macro_dir(macro_dir)

    df_output = pd.read_csv(os.path.join(macro_dir, "df_output.csv"))
    df_debt   = pd.read_csv(os.path.join(macro_dir, "df_debt.csv"))

    df_proj = pd.merge(df_output, df_debt, on="Year", how="left", suffixes=("", "_debt"))

    if "PTR_US" in df_proj.columns:
        df_proj["PTR_US"] = df_proj["PTR_US"].ffill().bfill()

    sfa_cols = [c for c in df_proj.columns if c.lower().startswith("sfa_")]
    for col in sfa_cols:
        df_proj.loc[df_proj["Year"] > 2024, col] = 0.0

    df_proj = df_proj[df_proj["Year"] > 1970].reset_index(drop=True)
    return df_proj


def _load_coefs(macro_dir: str, model_name: str) -> Dict[str, float]:
    """Load coefficient CSV → dict {coefficient_name: value}."""
    path = os.path.join(macro_dir, f"{model_name}_coef.csv")
    if not os.path.exists(path):
        raise FileNotFoundError(f"Missing coefficient file: {path}")
    df = pd.read_csv(path)
    return dict(zip(df["coefficient"], df["value"].astype(float)))


def _load_resid(macro_dir: str, name: str) -> np.ndarray:
    """Load resid_<name>.csv → numpy array (25 rows × n_countries).
    The 'year' column is dropped; remaining columns are residuals."""
    path = os.path.join(macro_dir, f"resid_{name}.csv")
    if not os.path.exists(path):
        raise FileNotFoundError(f"Missing residual file: {path}")
    df = pd.read_csv(path)
    if "year" in df.columns:
        df = df.drop(columns=["year"])
    arr = df.values.astype(float)
    # Replace NaN with 0 so the simulation always runs
    arr = np.where(np.isnan(arr), 0.0, arr)
    return arr  # shape: (25, n_cols)


def load_model_data(rdata_path: str) -> Dict[str, object]:
    """
    Load all model coefficients and residuals from macro/ CSV files.

    Returns a dict with keys:
        coefs_dypot, coefs_y, coefs_pi_US, coefs_pi, coef_r_US, coef_r_DE,
        coefs_r, coefs_s_social, coefs_s_non_social,
        resid_dypot, resid_y, resid_pi_US, resid_pi, resid_r_US, resid_r_DE,
        resid_r, resid_s_social, resid_s_non_social
    """
    macro_dir = _macro_dir(rdata_path)
    _require_macro_dir(macro_dir)

    return {
        # Coefficients
        "coefs_dypot":       _load_coefs(macro_dir, "mod_dypot_restricted_OLS"),
        "coefs_y":           _load_coefs(macro_dir, "mod_y_restricted_OLS"),
        "coefs_pi_US":       _load_coefs(macro_dir, "mod_pi_US"),
        "coefs_pi":          _load_coefs(macro_dir, "mod_pi_restricted"),
        "coef_r_US":         _load_coefs(macro_dir, "mod_r_US"),
        "coef_r_DE":         _load_coefs(macro_dir, "mod_r_DE"),
        "coefs_r":           _load_coefs(macro_dir, "mod_r_restricted_OLS"),
        "coefs_s_social":    _load_coefs(macro_dir, "mod_s_social"),
        "coefs_s_non_social":_load_coefs(macro_dir, "mod_s_non_social"),
        # Residuals (25 × n_countries arrays)
        "resid_dypot":       _load_resid(macro_dir, "dypot"),
        "resid_y":           _load_resid(macro_dir, "y"),
        "resid_pi_US":       _load_resid(macro_dir, "pi_US"),
        "resid_pi":          _load_resid(macro_dir, "pi"),
        "resid_r_US":        _load_resid(macro_dir, "r_US"),
        "resid_r_DE":        _load_resid(macro_dir, "r_DE"),
        "resid_r":           _load_resid(macro_dir, "r"),
        "resid_s_social":    _load_resid(macro_dir, "s_social"),
        "resid_s_non_social":_load_resid(macro_dir, "s_non_social"),
    }


