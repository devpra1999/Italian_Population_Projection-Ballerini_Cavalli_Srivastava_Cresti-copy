# Demographic ratio computation from population projection
# ---------------------------------------------------------------------------

def compute_demo_ratios_from_projection(
    population_by_age_mean: pd.DataFrame,
) -> Dict[str, pd.DataFrame]:
    """
    From population_by_age_mean (output of the demographic projection),
    compute the macro-relevant demographic variables for Italy per scenario.

    Returns {scenario_label: DataFrame(year, N_Y, N_M1, N_M2, N_R, N,
                                       MY, YM, D, D_Y, D_R, n, dn)}.
    """
    pop = population_by_age_mean.copy()
    grouped = pop.groupby(["scenario", "year", "age"])["population"].sum().reset_index()

    results: Dict[str, pd.DataFrame] = {}

    for scenario, sdf in grouped.groupby("scenario"):
        rows = []
        for year, ydf in sdf.groupby("year"):
            ages = ydf["age"].values
            pops = ydf["population"].values

            N_Y  = pops[ages < 20].sum()
            N_M1 = pops[(ages >= 20) & (ages < 45)].sum()
            N_M2 = pops[(ages >= 45) & (ages < 65)].sum()
            N_R  = pops[ages >= 65].sum()
            N    = N_Y + N_M1 + N_M2 + N_R
            denom = N_M1 + N_M2 if (N_M1 + N_M2) > 0 else np.nan

            rows.append({
                "year": year,
                "N_Y": N_Y, "N_M1": N_M1, "N_M2": N_M2, "N_R": N_R, "N": N,
                "MY":  N_M2 / N_M1 if N_M1 > 0 else np.nan,
                "YM":  N_M1 / N_M2 if N_M2 > 0 else np.nan,
                "D":   (N_Y + N_R) / denom if denom else np.nan,
                "D_Y": N_Y / denom          if denom else np.nan,
                "D_R": N_R / denom          if denom else np.nan,
                "n":   np.log(N)             if N > 0 else np.nan,
            })

        df_s = pd.DataFrame(rows).sort_values("year").reset_index(drop=True)
        df_s["dn"] = df_s["n"].diff()
        results[scenario] = df_s

    return results


