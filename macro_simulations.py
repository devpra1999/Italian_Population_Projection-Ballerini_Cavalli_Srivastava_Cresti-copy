def run_macro_simulations(
    df_proj: pd.DataFrame,
    italy_demo_by_scenario: Dict[str, pd.DataFrame],
    model_data: Dict[str, object],
    num_sim: int = 300,
    curr_year: int = 2024,
) -> Dict[str, Dict[str, pd.DataFrame]]:
    """
    Run the 6-country macroeconomic Monte Carlo simulation for each demographic
    scenario. Italy's demographic variables come from italy_demo_by_scenario;
    all other countries use df_proj values (from estimations.RData).

    model_data: output of load_model_data().

    Returns {scenario_label: {variable_name: DataFrame(year, mean, lower, upper)}}.
    Variables: dy, g, pi, ir, b, s, s_social, s_non_social, snowball, ygap.
    """
    # Unpack coefficients
    COEFS_DYPOT       = model_data["coefs_dypot"]
    COEFS_Y           = model_data["coefs_y"]
    COEFS_PI_US       = model_data["coefs_pi_US"]
    COEFS_PI          = model_data["coefs_pi"]
    COEF_R_US         = model_data["coef_r_US"]
    COEF_R_DE         = model_data["coef_r_DE"]
    COEFS_R           = model_data["coefs_r"]
    COEFS_S_SOCIAL    = model_data["coefs_s_social"]
    COEFS_S_NON_SOCIAL= model_data["coefs_s_non_social"]

    # Unpack residuals (25 × n_cols arrays)
    R_DYPOT    = model_data["resid_dypot"]      # (25, 6)
    R_Y        = model_data["resid_y"]          # (25, 6)
    R_PI_US    = model_data["resid_pi_US"].ravel()  # (25,)
    R_PI       = model_data["resid_pi"]         # (25, 5) non-US
    R_R_US     = model_data["resid_r_US"].ravel()   # (25,)
    R_R_DE     = model_data["resid_r_DE"].ravel()   # (25,)
    R_R        = model_data["resid_r"]          # (25, 4) peripheral
    R_S_SOC    = model_data["resid_s_social"]   # (25, 6)
    R_S_NS     = model_data["resid_s_non_social"]   # (25, 6)

    # Country-index helpers
    def _cidx(country, lst=COUNTRY_ORDER):
        return lst.index(country)

    # Projection rows
    curr_row = df_proj.index[df_proj["Year"] == curr_year]
    if len(curr_row) == 0:
        raise ValueError(f"curr_year={curr_year} not found in df_proj.")
    curr_idx  = curr_row[0]
    proj_df   = df_proj.iloc[curr_idx + 1:].reset_index(drop=True)
    proj_years = proj_df["Year"].values.astype(int)
    n_proj    = len(proj_df)

    if n_proj == 0:
        raise ValueError("No projection rows after curr_year in df_proj.")

    n_resid = R_DYPOT.shape[0]   # 25
    rng = np.random.default_rng()
    sample_idx = rng.integers(0, n_resid, size=(n_proj, num_sim))  # (n_proj, num_sim)

    def _init(col: str) -> float:
        row = df_proj[df_proj["Year"] == curr_year]
        if col in row.columns:
            v = row[col].iloc[0]
            return float(v) if pd.notna(v) else 0.0
        return 0.0

    def _proj_val(col: str, i: int) -> float:
        if col in proj_df.columns:
            v = proj_df[col].iloc[i]
            return float(v) if pd.notna(v) else 0.0
        return 0.0

    # Map residual column names → indices for panel models
    # (column names in the CSV may be "Germany", "Italy", ... or "France_ygap_Italy", etc.)
    def _build_col_idx(arr: np.ndarray, candidates: list) -> Dict[str, int]:
        """Find which column of arr corresponds to each country name."""
        # The R residual matrix uses country names as colnames
        return {c: j for j, c in enumerate(candidates) if j < arr.shape[1]}

    # For panel residuals from systemfit, columns match COUNTRY_ORDER (6 cols)
    # For peripheral spread model, columns match PERIPHERAL (4 cols)
    dypot_cidx = _build_col_idx(R_DYPOT, COUNTRY_ORDER)
    y_cidx     = _build_col_idx(R_Y, COUNTRY_ORDER)
    pi_cidx    = _build_col_idx(R_PI, COUNTRY_ORDER[1:])   # non-US
    r_cidx     = _build_col_idx(R_R, PERIPHERAL)
    ss_cidx    = _build_col_idx(R_S_SOC, COUNTRY_ORDER)
    sns_cidx   = _build_col_idx(R_S_NS, COUNTRY_ORDER)

    all_results: Dict[str, Dict[str, pd.DataFrame]] = {}

    for scenario, italy_demo in italy_demo_by_scenario.items():
        italy_by_year = italy_demo.set_index("year")

        italy_out: Dict[str, np.ndarray] = {k: np.zeros((n_proj, num_sim))
                                             for k in VAR_LABELS}

        # Cross-country linkage arrays
        ir_mat_US      = np.zeros((n_proj, num_sim))
        pi_mat_US      = np.zeros((n_proj, num_sim))
        ir_mat_Germany = np.zeros((n_proj, num_sim))
        b_mat_Germany  = np.zeros((n_proj, num_sim))

        for c in COUNTRY_ORDER:
            # Running lags as (num_sim,) arrays
            y_lag_v    = np.full(num_sim, _init(f"y_{c}"))
            ypot_lag_v = np.full(num_sim, _init(f"ypot_{c}"))
            ygap_lag_v = np.full(num_sim, _init(f"ygap_{c}"))
            pi_lag_v   = np.full(num_sim, _init(f"pi_{c}"))
            ir_lag_v   = np.full(num_sim, _init(f"IR_{c}"))
            b_lag_v    = np.full(num_sim, _init(f"b_{c}"))
            b_de_init  = _init("b_Germany")

            dypot_mat    = np.zeros((n_proj, num_sim))
            dy_mat       = np.zeros((n_proj, num_sim))
            y_mat        = np.zeros((n_proj, num_sim))
            ypot_mat     = np.zeros((n_proj, num_sim))
            ygap_mat     = np.zeros((n_proj, num_sim))
            pi_mat       = np.zeros((n_proj, num_sim))
            ir_mat_c     = np.zeros((n_proj, num_sim))
            s_social_mat = np.zeros((n_proj, num_sim))
            s_ns_mat     = np.zeros((n_proj, num_sim))
            s_mat_c      = np.zeros((n_proj, num_sim))
            b_mat_c      = np.zeros((n_proj, num_sim))
            snowball_mat = np.zeros((n_proj, num_sim))

            for i in range(n_proj):
                year = proj_years[i]
                si   = sample_idx[i]  # (num_sim,) row-indices into resid arrays

                # --- Residual draws (shape: (num_sim,)) ---
                e_dypot = R_DYPOT[si, dypot_cidx.get(c, 0)]
                e_y     = R_Y[si, y_cidx.get(c, 0)]
                e_ss    = R_S_SOC[si, ss_cidx.get(c, 0)]
                e_sns   = R_S_NS[si, sns_cidx.get(c, 0)]

                # --- Demographic variables ---
                if c == "Italy":
                    row_d = italy_by_year.loc[year] if year in italy_by_year.index else italy_by_year.iloc[-1]
                    dn_c  = float(row_d["dn"])  if pd.notna(row_d["dn"])  else 0.0
                    YM_c  = float(row_d["YM"])  if pd.notna(row_d["YM"])  else 0.0
                    D_R_c = float(row_d["D_R"]) if pd.notna(row_d["D_R"]) else 0.0
                    D_c   = float(row_d["D"])   if pd.notna(row_d["D"])   else 0.0
                    MY_c  = float(row_d["MY"])  if pd.notna(row_d["MY"])  else 0.0
                else:
                    dn_c  = _proj_val(f"dn_{c}",  i)
                    YM_c  = _proj_val(f"YM_{c}",  i)
                    D_R_c = _proj_val(f"D_R_{c}", i)
                    D_c   = _proj_val(f"D_{c}",   i)
                    MY_c  = _proj_val(f"MY_{c}",  i)

                # --- Growth ---
                dypot_mat[i] = (COEFS_DYPOT.get(f"{c}_dn_{c}", 0)  * dn_c
                                + COEFS_DYPOT.get(f"{c}_YM_{c}", 0)  * YM_c
                                + COEFS_DYPOT.get(f"{c}_D_R_{c}", 0) * D_R_c
                                + e_dypot)

                dy_mat[i] = (COEFS_Y.get(f"{c}_dypot_{c}", 0)    * dypot_mat[i]
                             + COEFS_Y.get(f"{c}_ygap_lag_{c}", 0) * ygap_lag_v
                             + COEFS_Y.get(f"{c}_D_{c}", 0)         * D_c
                             + e_y)

                y_mat[i]    = y_lag_v    + dy_mat[i]
                ypot_mat[i] = ypot_lag_v + dypot_mat[i]
                ygap_mat[i] = y_mat[i] - ypot_mat[i]

                # --- Inflation & interest rate ---
                if c == "US":
                    PTR_US = _proj_val("PTR_US", i) or 0.02
                    e_pi_US = R_PI_US[si]
                    e_r_US  = R_R_US[si]

                    pi_mat[i] = (COEFS_PI_US.get("pi_lag_US", 0) * pi_lag_v
                                 + COEFS_PI_US.get("PTR_US", 0)   * PTR_US
                                 + e_pi_US)

                    ir_mat_c[i] = (COEF_R_US.get("(Intercept)", 0)
                                   + COEF_R_US.get("dypot_US", 0) * dypot_mat[i]
                                   + COEF_R_US.get("PTR_US", 0)   * PTR_US
                                   + COEF_R_US.get("MY_US", 0)    * MY_c
                                   + e_r_US)

                    ir_mat_US[i] = ir_mat_c[i]
                    pi_mat_US[i] = pi_mat[i]

                elif c == "Germany":
                    j_pi  = pi_cidx.get(c, 0)
                    e_pi  = R_PI[si, j_pi]
                    e_rDE = R_R_DE[si]

                    pi_mat[i] = (COEFS_PI.get(f"{c}_pi_lag_{c}", 0) * pi_lag_v
                                 + COEFS_PI.get(f"{c}_pi_US", 0)     * pi_mat_US[i]
                                 + e_pi)

                    ir_mat_c[i] = (COEF_R_DE.get("(Intercept)", 0)
                                   + COEF_R_DE.get("IR_US", 0)          * ir_mat_US[i]
                                   + COEF_R_DE.get("lag_IR_Germany", 0)  * ir_lag_v
                                   + e_rDE)

                    ir_mat_Germany[i] = ir_mat_c[i]

                else:  # peripheral
                    j_pi  = pi_cidx.get(c, 0)
                    j_r   = r_cidx.get(c, 0)
                    e_pi  = R_PI[si, j_pi]
                    e_r   = R_R[si, j_r]

                    pi_mat[i] = (COEFS_PI.get(f"{c}_pi_lag_{c}", 0) * pi_lag_v
                                 + COEFS_PI.get(f"{c}_pi_US", 0)     * pi_mat_US[i]
                                 + e_pi)

                    b_diff_lag = b_lag_v - (b_de_init if i == 0 else b_mat_Germany[i - 1])
                    spread = (COEFS_R.get(f"{c}_(Intercept)", 0)
                              + COEFS_R.get(f"{c}_b_diff_lag_{c}", 0) * b_diff_lag
                              + e_r)
                    ir_mat_c[i] = spread + ir_mat_Germany[i]

                # --- Fiscal surplus ---
                s_social_mat[i] = (COEFS_S_SOCIAL.get(f"{c}_(Intercept)", 0)
                                   + COEFS_S_SOCIAL.get(f"{c}_ygap_{c}", 0) * ygap_mat[i]
                                   + COEFS_S_SOCIAL.get(f"{c}_D_R_{c}", 0)  * D_R_c
                                   + e_ss)

                s_ns_mat[i] = (COEFS_S_NON_SOCIAL.get(f"{c}_(Intercept)", 0)
                               + COEFS_S_NON_SOCIAL.get(f"{c}_ygap_{c}", 0)  * ygap_mat[i]
                               + COEFS_S_NON_SOCIAL.get(f"{c}_b_lag_{c}", 0) * b_lag_v
                               + e_sns)

                s_mat_c[i] = s_social_mat[i] + s_ns_mat[i]

                # --- Debt dynamics ---
                g_nom       = dy_mat[i] + pi_mat[i]
                b_mat_c[i]  = -s_mat_c[i] + (1 + ir_mat_c[i]) / (1 + g_nom) * b_lag_v
                snowball_mat[i] = (ir_mat_c[i] - g_nom) / (1 + g_nom) * b_lag_v

                # --- Update lags ---
                y_lag_v    = y_mat[i].copy()
                ypot_lag_v = ypot_mat[i].copy()
                ygap_lag_v = ygap_mat[i].copy()
                pi_lag_v   = pi_mat[i].copy()
                ir_lag_v   = ir_mat_c[i].copy()
                b_lag_v    = b_mat_c[i].copy()

            if c == "Germany":
                b_mat_Germany = b_mat_c.copy()

            if c == "Italy":
                italy_out["dy"]           = dy_mat
                italy_out["g"]            = dy_mat + pi_mat
                italy_out["pi"]           = pi_mat
                italy_out["ir"]           = ir_mat_c
                italy_out["ygap"]         = ygap_mat
                italy_out["s"]            = s_mat_c
                italy_out["s_social"]     = s_social_mat
                italy_out["s_non_social"] = s_ns_mat
                italy_out["b"]            = b_mat_c
                italy_out["snowball"]     = snowball_mat

        # --- Summarise (90% CI, z = 1.645) ---
        z = 1.645
        summary: Dict[str, pd.DataFrame] = {}
        for var, mat in italy_out.items():
            mean_v = mat.mean(axis=1)
            std_v  = mat.std(axis=1)
            summary[var] = pd.DataFrame({
                "year":  proj_years,
                "mean":  mean_v,
                "lower": mean_v - z * std_v,
                "upper": mean_v + z * std_v,
            })

        all_results[scenario] = summary

    return all_results


