# =============================================================================
# MIGRATION MODULE - OUR BASELINE WITH AGE-SEX ALLOCATION
# =============================================================================
# Reading guide
# -------------
# This script builds our own baseline for immigration, emigration, and net
# migration. ISTAT, Eurostat, and UN are not used to build the forecast here;
# they are only used later as benchmarks in the plotting script.
#
# The input flows are observed by broad age group. The script therefore:
#   - removes total rows if they exist;
#   - reconstructs annual totals as the sum of age-band counts;
#   - forecasts total immigration and emigration with our own time-series logic;
#   - builds age-sex schedules by combining recent age-band shares, a smooth
#     Rogers-Castro-style single-age template, and the latest Italian/foreign
#     population age-sex structure;
#   - checks that the reconstructed single-age counts sum back exactly to the
#     original broad age-band totals.
# =============================================================================

#!/usr/bin/env python3
"""
02_fit_forecast_migration_own_method_age_sex.py

Own-method migration forecast with age-sex reconstruction.

This script keeps ISTAT, Eurostat and UN out of the baseline. They are used only
by the plotting script as external benchmarks.

Method implemented
------------------
1. Total flows:
   - immigration is forecast from a damped recent log trend;
   - emigration is forecast from a damped recent log trend;
   - net migration is immigration minus emigration;
   - uncertainty is generated by simulations.

2. Age-sex detail:
   - observed broad age-range counts are read by flow, origin, sex and year;
   - recent broad age/origin/sex shares are estimated separately for immigration
     and emigration;
   - forecast total flows are allocated using those recent shares;
   - each broad age range is expanded to single ages 0-100 with a smooth
     Rogers-Castro-style template multiplied by the relevant population structure:
       Origine=Italia       -> italiani.csv
       Origine=Paesi esteri -> stranieri.csv
   - by default, a smooth-and-rake step is used after the first expansion. This is
     important because a purely independent rescaling inside each broad band can
     create artificial cliffs at 17/18, 39/40 and 64/65. The smooth-and-rake step
     smooths the single-age curve across band boundaries and then rakes it back
     to the original broad age-band totals, so each broad age-range total is still
     exactly preserved after expansion.

Default output:
    output/migration/own_method_age_sex
"""

