# into the child band.
#
# The default is a compromise:
# - start 0-17 from the relevant recent child population structure;
# - still smooth across 17/18 so the adult migration peak is anticipated without
#   producing a cliff at exactly age 18;
# - rake each broad age band back to its original total after every smoothing
