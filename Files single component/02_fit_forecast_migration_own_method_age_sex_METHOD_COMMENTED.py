def append_net_single_age(mean_single: pd.DataFrame) -> pd.DataFrame:
    """
    Compute net migration at single age and sex by subtracting emigration from immigration.
    """
    key = ["year", "origin", "population_citizenship", "sex", "age"]
    imm = mean_single[mean_single["flow"].eq("immigration")][key + ["count"]].rename(columns={"count": "immigration"})
    emi = mean_single[mean_single["flow"].eq("emigration")][key + ["count"]].rename(columns={"count": "emigration"})
    net = imm.merge(emi, on=key, how="outer").fillna({"immigration": 0.0, "emigration": 0.0})
    net["count"] = net["immigration"] - net["emigration"]
    net["flow"] = "net_migration"
    net["age_band"] = "single_age_net"
    net["age_min"] = net["age"]
    net["age_max"] = net["age"]
    net["single_age_share_inside_band"] = np.nan
    net["population_year_used"] = np.nan
    cols = [
        "flow", "year", "origin", "population_citizenship", "sex", "age", "age_band", "age_min", "age_max",
        "single_age_share_inside_band", "count", "population_year_used",
    ]
    return pd.concat([mean_single[cols], net[cols]], ignore_index=True).sort_values(["flow", "year", "origin", "sex", "age"])


def append_net_age_bands(mean_bands: pd.DataFrame) -> pd.DataFrame:
    """
    Compute net migration by broad age band by subtracting emigration from immigration.
    """
    key = ["year", "origin", "population_citizenship", "sex", "age_band", "age_min", "age_max"]
    imm = mean_bands[mean_bands["flow"].eq("immigration")][key + ["count"]].rename(columns={"count": "immigration"})
    emi = mean_bands[mean_bands["flow"].eq("emigration")][key + ["count"]].rename(columns={"count": "emigration"})
    net = imm.merge(emi, on=key, how="outer").fillna({"immigration": 0.0, "emigration": 0.0})
    net["count"] = net["immigration"] - net["emigration"]
    net["flow"] = "net_migration"
    keep_cols = ["flow", *key, "count"]
    return pd.concat([mean_bands[keep_cols], net[keep_cols]], ignore_index=True).sort_values(
        ["flow", "year", "origin", "sex", "age_min"]
    )


def summarize_age_sex_intervals(
    total_sim: pd.DataFrame,
    single_age_shares: pd.DataFrame,
    age_band_shares: pd.DataFrame,
) -> tuple[pd.DataFrame, pd.DataFrame]:
    years = sorted(total_sim["year"].unique())
    quantiles = [0.05, 0.10, 0.25, 0.50, 0.75, 0.90, 0.95]
    qnames = ["p05", "p10", "p25", "p50", "p75", "p90", "p95"]
    single_rows = []
    band_rows = []

    sim_by_year = {int(y): g.sort_values("sim") for y, g in total_sim.groupby("year")}

    for year in years:
        sims = sim_by_year[int(year)]
        imm_sims = sims["immigration"].to_numpy(dtype=float)
        emi_sims = sims["emigration"].to_numpy(dtype=float)

        year_single = single_age_shares[single_age_shares["year"].eq(year)].copy()
        for flow, sim_values in [("immigration", imm_sims), ("emigration", emi_sims)]:
            g = year_single[year_single["flow"].eq(flow)].copy()
            shares = g["share_of_flow_single_age"].to_numpy(dtype=float)
            q = np.quantile(sim_values[:, None] * shares[None, :], quantiles, axis=0)
            mean = float(sim_values.mean()) * shares
            for idx, (_, row) in enumerate(g.iterrows()):
                out = {
                    "year": int(year),
                    "flow": flow,
                    "origin": row["origin"],
                    "population_citizenship": row["population_citizenship"],
                    "sex": row["sex"],
                    "age": int(row["age"]),
                    "age_band": row["age_band"],
                    "mean": float(mean[idx]),
                    "interval_method": "total_flow_simulation_with_fixed_age_sex_shares",
                }
                for qname, qvalues in zip(qnames, q):
                    out[qname] = float(qvalues[idx])
                single_rows.append(out)

        wide_single = year_single.pivot_table(
            index=["origin", "population_citizenship", "sex", "age"],
            columns="flow",
            values="share_of_flow_single_age",
            aggfunc="sum",
            fill_value=0.0,
        ).reset_index()
        for col in ["immigration", "emigration"]:
            if col not in wide_single:
                wide_single[col] = 0.0
        imm_share = wide_single["immigration"].to_numpy(dtype=float)
        emi_share = wide_single["emigration"].to_numpy(dtype=float)
        net_values = imm_sims[:, None] * imm_share[None, :] - emi_sims[:, None] * emi_share[None, :]
        q = np.quantile(net_values, quantiles, axis=0)
        mean = net_values.mean(axis=0)
        for idx, (_, row) in enumerate(wide_single.iterrows()):
            out = {
                "year": int(year),
                "flow": "net_migration",
                "origin": row["origin"],
                "population_citizenship": row["population_citizenship"],
                "sex": row["sex"],
                "age": int(row["age"]),
                "age_band": "single_age_net",
                "mean": float(mean[idx]),
                "interval_method": "component_total_flow_simulation_with_fixed_age_sex_shares",
            }
            for qname, qvalues in zip(qnames, q):
                out[qname] = float(qvalues[idx])
            single_rows.append(out)

        year_bands = age_band_shares[age_band_shares["year"].eq(year)].copy()
        for flow, sim_values in [("immigration", imm_sims), ("emigration", emi_sims)]:
            g = year_bands[year_bands["flow"].eq(flow)].copy()
            shares = g["share_of_flow"].to_numpy(dtype=float)
            q = np.quantile(sim_values[:, None] * shares[None, :], quantiles, axis=0)
            mean = float(sim_values.mean()) * shares
            for idx, (_, row) in enumerate(g.iterrows()):
                out = {
                    "year": int(year),
                    "flow": flow,
                    "origin": row["origin"],
                    "population_citizenship": row["population_citizenship"],
                    "sex": row["sex"],
                    "age_band": row["age_band"],
                    "age_min": int(row["age_min"]),
                    "age_max": int(row["age_max"]),
                    "mean": float(mean[idx]),
                    "interval_method": "total_flow_simulation_with_fixed_age_band_shares",
                }
                for qname, qvalues in zip(qnames, q):
                    out[qname] = float(qvalues[idx])
                band_rows.append(out)

        wide_band = year_bands.pivot_table(
            index=["origin", "population_citizenship", "sex", "age_band", "age_min", "age_max"],
            columns="flow",
            values="share_of_flow",
            aggfunc="sum",
            fill_value=0.0,
        ).reset_index()
        for col in ["immigration", "emigration"]:
            if col not in wide_band:
                wide_band[col] = 0.0
        imm_share = wide_band["immigration"].to_numpy(dtype=float)
        emi_share = wide_band["emigration"].to_numpy(dtype=float)
        net_values = imm_sims[:, None] * imm_share[None, :] - emi_sims[:, None] * emi_share[None, :]
        q = np.quantile(net_values, quantiles, axis=0)
        mean = net_values.mean(axis=0)
        for idx, (_, row) in enumerate(wide_band.iterrows()):
            out = {
                "year": int(year),
                "flow": "net_migration",
                "origin": row["origin"],
                "population_citizenship": row["population_citizenship"],
                "sex": row["sex"],
                "age_band": row["age_band"],
                "age_min": int(row["age_min"]),
                "age_max": int(row["age_max"]),
                "mean": float(mean[idx]),
                "interval_method": "component_total_flow_simulation_with_fixed_age_band_shares",
            }
            for qname, qvalues in zip(qnames, q):
                out[qname] = float(qvalues[idx])
            band_rows.append(out)

    return pd.DataFrame(single_rows), pd.DataFrame(band_rows)


def save_component_total_files(total_mean: pd.DataFrame, total_intervals: pd.DataFrame, outdir: Path) -> None:
    """
    Save separate total-flow outputs for immigration, emigration, and net migration.
    """
    for flow in FLOW_ORDER:
        total_mean[["year", flow, "method", "scenario", "citizenship_scope"]].rename(columns={flow: "count"}).assign(flow=flow)[
            ["year", "flow", "count", "method", "scenario", "citizenship_scope"]
        ].to_csv(outdir / f"{flow}_own_method_age_sex_mean.csv", index=False)
        total_intervals[total_intervals["flow"].eq(flow)].to_csv(outdir / f"{flow}_own_method_age_sex_intervals.csv", index=False)


def total_check(single_age_mean: pd.DataFrame, total_mean: pd.DataFrame) -> pd.DataFrame:
    """
    Check whether the age-sex schedules sum back to the total migration forecasts.
    """
    totals = single_age_mean.groupby(["year", "flow"], as_index=False)["count"].sum().rename(columns={"count": "single_age_sum"})
    total_long = total_mean.melt(id_vars=["year"], value_vars=FLOW_ORDER, var_name="flow", value_name="total_forecast")
    out = totals.merge(total_long, on=["year", "flow"], how="left")
    out["difference"] = out["single_age_sum"] - out["total_forecast"]
    return out.sort_values(["flow", "year"])


