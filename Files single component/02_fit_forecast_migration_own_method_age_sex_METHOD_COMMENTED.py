    parser.add_argument("--emigration-trend-damping", type=float, default=DEFAULT_EMIGRATION_TREND_DAMPING)
    parser.add_argument("--immigration-slope-cap", type=float, default=DEFAULT_IMMIGRATION_SLOPE_CAP)
    parser.add_argument("--emigration-slope-cap", type=float, default=DEFAULT_EMIGRATION_SLOPE_CAP)
    parser.add_argument(
        "--single-age-method",
        choices=["smooth_rake", "band_rescaled"],
        default=DEFAULT_SINGLE_AGE_METHOD,
        help=(
            "smooth_rake is the default because it avoids artificial age-band boundary spikes while "
            "still preserving every broad age-band total exactly. band_rescaled reproduces the literal "
            "independent within-band Rogers-Castro allocation."
        ),
    )
    parser.add_argument(
        "--age-smoothing-iterations",
        type=int,
        default=DEFAULT_SMOOTHING_ITERATIONS,
        help="Number of smooth-and-rake iterations used when --single-age-method=smooth_rake.",
    )
    parser.add_argument(
        "--age-smoothing-strength",
        type=float,
        default=DEFAULT_SMOOTHING_STRENGTH,
        help="Blend weight for each smoothing pass. 0 keeps the literal band-rescaled curve; 1 uses the full smoothed pass.",
    )
    parser.add_argument(
        "--child-age-method",
        choices=["population_bridge", "population_only", "template_population"],
        default=DEFAULT_CHILD_AGE_METHOD,
        help=(
            "How to split and smooth the 0-17 broad age band. population_bridge starts from "
            "italiani.csv/stranieri.csv inside 0-17, then softly smooths across 17/18 while anchoring "
            "children back to that population profile. population_only keeps 0-17 exactly population-shaped "
            "and blocks smoothing across 17/18. template_population also multiplies children by the "
            "Rogers-Castro template, which can pull the child band toward age 17."
        ),
    )
    parser.add_argument(
        "--child-bridge-anchor",
        type=float,
        default=DEFAULT_CHILD_BRIDGE_ANCHOR,
        help=(
            "Only used with --child-age-method=population_bridge. Higher values keep 0-17 closer to the "
            "recent population profile; lower values smooth more strongly toward the young-adult migration peak."
        ),
    )
    args = parser.parse_args()

    outdir = resolve_output_path(args.output_dir)
    outdir.mkdir(parents=True, exist_ok=True)

    immigration_age_bands = read_flow_age_bands(args.immigration_input, "immigration")
    emigration_age_bands = read_flow_age_bands(args.emigration_input, "emigration")
    observed_age_bands = pd.concat([immigration_age_bands, emigration_age_bands], ignore_index=True)
    observed_totals = aggregate_observed_totals(observed_age_bands)

    immigration_trend_years = parse_year_list(args.immigration_trend_years, DEFAULT_IMMIGRATION_TREND_YEARS)
    emigration_trend_years = parse_year_list(args.emigration_trend_years, DEFAULT_EMIGRATION_TREND_YEARS)
    recent_level_years = parse_year_list(args.recent_level_years, DEFAULT_RECENT_LEVEL_YEARS)
    age_share_years = parse_year_list(args.age_share_years, DEFAULT_RECENT_LEVEL_YEARS)
    immigration_trend_damping = args.immigration_trend_damping if args.trend_damping is None else args.trend_damping
    emigration_trend_damping = args.emigration_trend_damping if args.trend_damping is None else args.trend_damping

    total_mean, total_intervals, total_sim, params = build_total_forecast(
        observed_totals,
        args.start_year,
        args.end_year,
        immigration_trend_years,
        emigration_trend_years,
        recent_level_years,
        args.n_sim,
        args.random_seed,
        immigration_trend_damping,
        emigration_trend_damping,
        args.immigration_slope_cap,
        args.emigration_slope_cap,
    )

