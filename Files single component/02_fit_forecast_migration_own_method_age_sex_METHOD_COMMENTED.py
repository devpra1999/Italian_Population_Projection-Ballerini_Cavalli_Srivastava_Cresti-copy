# The original literal method is:
#     broad age band total * Rogers-Castro-population share inside that band.
# That is mathematically correct if the only goal is exact preservation of broad
# age-band totals, but it can create artificial spikes at age-band boundaries. The
# default below keeps exact broad-band preservation but smooths across boundaries.
